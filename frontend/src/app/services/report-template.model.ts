// Mirrors backend: com.cssweng.reportbuilder.model.ReportTemplate

export interface School {
  id: string;       // UUID
  name?: string;     // adjust once School.java is confirmed
}

export type TemplateStudentType = 'K12' | 'COLLEGE' | 'ADMISSIONS';

// Whether a template is generated per-student (roster, ID card,
// certificate of enrollment - needs a TemplateStudentType to know which
// merge fields apply) or is a data-driven report not tied to any one
// student (financial summary, enrollment stats, headcount breakdown -
// no student type makes sense here at all).
//
// NOTE: this field may not exist on older backend records yet. Until the
// backend is confirmed to send/persist it, callers should fall back to
// inferring DATA from an absent studentType (see templates.ts) rather
// than assuming this field is always populated.
export type TemplateReportKind = 'STUDENT' | 'DATA';

export interface ReportTemplate {
  id?: string;              // UUID, generated by backend — omit when creating
  name: string;
  configuration: string;    // JSON string from the WYSIWYG editor (stringify before sending)
  school: School;            // or use schoolId: string if backend expects a flat FK on create
  lastOpenedAt?: string;     // ISO timestamp, set by the backend whenever the template is opened
  thumbnailUrl?: string;     // set by the backend after a thumbnail is uploaded
  studentType?: TemplateStudentType;  // which roster this template is meant for; nullable for older templates AND for DATA-kind templates
  reportKind?: TemplateReportKind;    // see TemplateReportKind note above
}

// Convenience type for POST payloads where you may only have the school's id on hand
export interface CreateReportTemplateRequest {
  name: string;
  configuration: string;
  schoolId: string;
  studentType?: TemplateStudentType;
  reportKind?: TemplateReportKind;
}